function normalize(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]/g, "")
}

/**
 * Filter Sri Lankan bus towns letter by letter.
 * Prioritizes:
 * 1. Exact match or startsWith prefix match
 * 2. Word boundary match (e.g. searching "Colombo" or "Pettah" or "Kottawa")
 * 3. Substring match
 */
export function filterTowns(
  query: string,
  extraTowns: string[] = [],
  limit = 12
): string[] {
  const trimmed = query.trim().toLowerCase()
  if (!trimmed) return []

  const normQ = normalize(trimmed)
  const allTowns = Array.from(new Set([...extraTowns, ...SRI_LANKAN_TOWNS]))

  const exact: string[] = []
  const startsWith: string[] = []
  const wordStart: string[] = []
  const contains: string[] = []

  for (const town of allTowns) {
    const lower = town.toLowerCase()
    const norm = normalize(town)

    if (lower === trimmed || norm === normQ) {
      exact.push(town)
    } else if (lower.startsWith(trimmed) || norm.startsWith(normQ)) {
      startsWith.push(town)
    } else {
      // Check word boundaries (e.g. "(Colombo)" or "Bay" or "(Kottawa)")
      const words = lower.split(/[\s\-()]+/).filter(Boolean)
      if (words.some((w) => w.startsWith(trimmed))) {
        wordStart.push(town)
      } else if (lower.includes(trimmed) || norm.includes(normQ)) {
        contains.push(town)
      }
    }
  }

  exact.sort((a, b) => a.localeCompare(b))
  startsWith.sort((a, b) => a.localeCompare(b))
  wordStart.sort((a, b) => a.localeCompare(b))
  contains.sort((a, b) => a.localeCompare(b))

  return [...exact, ...startsWith, ...wordStart, ...contains].slice(0, limit)
}
